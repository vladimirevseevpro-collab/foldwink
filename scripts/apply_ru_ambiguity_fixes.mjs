const DIRS = ['puzzles/ru/pool', 'puzzles/ru-drafts'];
let total = 0;
let skipped = 0;
const log = [];

for (const dir of DIRS) {
  for (const [id, oldW, newW, label] of REPLACEMENTS) {
    const file = path.join(dir, `${id}.json`);
    if (!fs.existsSync(file)) { log.push(`MISS: ${file}`); skipped++; continue; }
    const raw = fs.readFileSync(file, 'utf8');
    const puzzle = JSON.parse(raw);
    const group = puzzle.groups.find(g => g.label === label);
    if (!group) { log.push(`NO-GROUP: ${file} label="${label}"`); skipped++; continue; }
    const idx = group.items.indexOf(oldW);
    if (idx === -1) { log.push(`NO-ITEM: ${file} group="${label}" item="${oldW}"`); skipped++; continue; }
    group.items[idx] = newW;
    // Preserve formatting style: drafts use compact one-line arrays; pool uses pretty 2-space
    const isDraft = dir.includes('ru-drafts');
    let out;
    if (isDraft) {
      // Compact: mimic original hand style
      const lines = ['{'];
      lines.push(`  "id": ${JSON.stringify(puzzle.id)},`);
      lines.push(`  "title": ${JSON.stringify(puzzle.title)},`);
      lines.push(`  "difficulty": ${JSON.stringify(puzzle.difficulty)},`);
      lines.push(`  "meta": ${JSON.stringify(puzzle.meta)},`);
      lines.push(`  "groups": [`);
      const gl = puzzle.groups.map(g =>
        `    { "id": ${JSON.stringify(g.id)}, "label": ${JSON.stringify(g.label)}, "items": ${JSON.stringify(g.items)} }`
      );
      lines.push(gl.join(',\n'));
      lines.push(`  ]`);
      lines.push(`}`);
      out = lines.join('\n') + '\n';
    } else {
      out = JSON.stringify(puzzle, null, 2) + '\n';
    }
    fs.writeFileSync(file, out, 'utf8');
    log.push(`OK: ${file} :: "${oldW}" → "${newW}"`);
    total++;
  }
}

console.log(log.join('\n'));
console.log(`\nApplied: ${total} edits across ${DIRS.length} dirs (expected ${REPLACEMENTS.length * DIRS.length}). Skipped: ${skipped}.`);
